// Simple HTML sanitizer to prevent XSS when using innerHTML
// Escapes HTML special characters in user/data-driven strings
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
